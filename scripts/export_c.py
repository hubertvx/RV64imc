#!/usr/bin/env python3
"""
Turn the quantized model into files the bare-metal C program can use.

  weights.bin   all 50 layers: int8 weights [N][K], int32 bias[N], int32 mult[N], int32 shift[N]
  vectors.bin   test vectors: for a few layers, the int8 input, the expected int32 accumulator
                and the expected int8 output
  model.h       layer table and vector table: sizes and byte offsets into the two blobs
  manifest.json same information plus the float scales, for Python-side tools

Everything is 8-byte aligned so the C code can load 8 int8 values with one 64-bit load
"""

import argparse
import glob
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from quantize_w8a8 import Model, as_matrix, preprocess, requantize   # same integer math as the check

DEFAULT_VECTOR_LAYERS = ("blocks_0_mlp_fc1", "blocks_0_attn_qkv")


class Blob:
    """Append-only byte buffer; every item starts on an 8-byte boundary."""

    def __init__(self):
        self.data = bytearray()

    def add(self, array, dtype):
        self.data += b"\0" * (-len(self.data) % 8)
        off = len(self.data)
        self.data += np.ascontiguousarray(array, dtype=dtype).tobytes()
        return off


def pack_weights(model, npz):
    blob, layers = Blob(), []
    for l in model.layers:
        d = {k: npz[f"{l['name']}__{k}"] for k in ("w_q", "b_q", "mult", "shift")}
        n, k = d["w_q"].shape
        layers.append({
            "name": l["name"], "N": n, "K": k,
            "w_off": blob.add(d["w_q"], "i1"),        # int8   [N][K]
            "b_off": blob.add(d["b_q"], "<i4"),       # int32  [N]
            "m_off": blob.add(d["mult"], "<i4"),      # int32  [N]
            "s_off": blob.add(d["shift"], "<i4"),     # int32  [N]
            "s_in": float(npz[f"{l['name']}__s_in"]), "s_out": float(npz[f"{l['name']}__s_out"]),
        })
    return blob, layers


def make_vectors(model, npz, layers, names, image):
    """For each named layer: int8 input, expected int32 accumulator, expected int8 output."""
    model.run(preprocess(image))
    by_name = {l["name"]: i for i, l in enumerate(model.layers)}
    blob, vectors = Blob(), []
    for name in names:
        i = by_name[name]
        l = model.layers[i]
        d = {k: npz[f"{name}__{k}"] for k in ("w_q", "b_q", "mult", "shift", "s_in")}
        x = as_matrix(model.get(l["in"]), l["op"])
        x_q = np.clip(np.round(x / d["s_in"]), -128, 127).astype(np.int8)
        acc = x_q.astype(np.int64) @ d["w_q"].T.astype(np.int64) + d["b_q"]
        assert np.abs(acc).max() < 2**31, "accumulator does not fit in int32"
        out = requantize(acc, d["mult"].astype(np.int64), d["shift"].astype(np.int64))
        vectors.append({
            "name": name, "layer": i, "M": x_q.shape[0],
            "x_off": blob.add(x_q, "i1"),
            "acc_off": blob.add(acc, "<i4"),
            "out_off": blob.add(out, "i1"),
        })
    return blob, vectors


def write_header(path, layers, vectors):
    with open(path, "w") as f:
        f.write("/* generated by scripts/export_c.py - do not edit */\n"
                "#ifndef MODEL_H\n#define MODEL_H\n#include <stdint.h>\n\n")
        f.write(f"#define NUM_LAYERS {len(layers)}\n#define NUM_VECTORS {len(vectors)}\n\n")
        f.write("/* One weight layer: C[m][n] = requant(bias[n] + sum_k x[m][k] * w[n][k]).\n"
                " * Offsets are in bytes into weights_blob: int8 w[N][K], int32 bias[N], mult[N], shift[N]. */\n"
                "typedef struct {\n    const char *name;\n    int N, K;\n"
                "    uint32_t w_off, b_off, m_off, s_off;\n} layer_t;\n\n")
        f.write("/* A test vector for layer `layer`: int8 x[M][K], expected int32 acc[M][N], expected int8 out[M][N]\n"
                " * (byte offsets into vectors_blob). */\n"
                "typedef struct {\n    const char *name;\n    int layer, M;\n"
                "    uint32_t x_off, acc_off, out_off;\n} vector_t;\n\n")
        f.write("extern const uint8_t weights_blob[];\nextern const uint8_t vectors_blob[];\n\n")
        f.write("static const layer_t layers[NUM_LAYERS] = {\n")
        for l in layers:
            f.write(f'    {{"{l["name"]}", {l["N"]}, {l["K"]}, {l["w_off"]}u, {l["b_off"]}u, {l["m_off"]}u, {l["s_off"]}u}},\n')
        f.write("};\n\nstatic const vector_t vectors[NUM_VECTORS] = {\n")
        for v in vectors:
            f.write(f'    {{"{v["name"]}", {v["layer"]}, {v["M"]}, {v["x_off"]}u, {v["acc_off"]}u, {v["out_off"]}u}},\n')
        f.write("};\n\n#endif\n")


def verify(out_dir, npz, layers):
    """Read the written files back and compare with the arrays in the .npz."""
    w = open(os.path.join(out_dir, "weights.bin"), "rb").read()
    for l in layers:
        n, k = l["N"], l["K"]
        for key, off, dtype, count in (("w_q", l["w_off"], "i1", n * k), ("b_q", l["b_off"], "<i4", n),
                                       ("mult", l["m_off"], "<i4", n), ("shift", l["s_off"], "<i4", n)):
            assert off % 8 == 0, f"{l['name']}.{key} not 8-byte aligned"
            got = np.frombuffer(w, dtype=dtype, count=count, offset=off)
            assert np.array_equal(got, npz[f"{l['name']}__{key}"].reshape(-1)), f"{l['name']}.{key} differs"


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser()
    ap.add_argument("--npz", default=os.path.join(here, "..", "models", "deit_tiny_int8.npz"))
    ap.add_argument("--model", default=os.path.join(here, "..", "models", "model.tflite"))
    ap.add_argument("--calib", default=os.path.join(here, "..", "data", "calib"))
    ap.add_argument("--out", default=os.path.join(here, "..", "build", "gen"))
    ap.add_argument("--vector-layers", nargs="+", default=list(DEFAULT_VECTOR_LAYERS))
    args = ap.parse_args()

    npz = np.load(args.npz)
    model = Model(args.model)
    image = sorted(glob.glob(os.path.join(args.calib, "*.jpg")))[-1]   # one of the images kept aside for checking

    wblob, layers = pack_weights(model, npz)
    vblob, vectors = make_vectors(model, npz, layers, args.vector_layers, image)

    os.makedirs(args.out, exist_ok=True)
    open(os.path.join(args.out, "weights.bin"), "wb").write(wblob.data)
    open(os.path.join(args.out, "vectors.bin"), "wb").write(vblob.data)
    write_header(os.path.join(args.out, "model.h"), layers, vectors)
    with open(os.path.join(args.out, "manifest.json"), "w") as f:
        json.dump({"image": os.path.basename(image), "layers": layers, "vectors": vectors}, f, indent=1)
    verify(args.out, npz, layers)

    out = os.path.normpath(args.out)
    print(f"{len(layers)} layers  -> {out}/weights.bin  ({len(wblob.data):,} bytes)")
    for v in vectors:
        print(f"vector {v['name']}: M={v['M']}")
    print(f"{len(vectors)} vectors -> {out}/vectors.bin  ({len(vblob.data):,} bytes)")
    print(f"model.h, manifest.json written; round-trip check of weights.bin passed")


if __name__ == "__main__":
    main()
